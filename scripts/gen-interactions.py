#!/usr/bin/env python3
"""gen-interactions - generate the interaction reference from source, and fail when it drifts.

Modelled on DeepSeek Harness's doc-sync discipline (docs/tool-catalog.md): the
catalog is GENERATED, verified fresh by CI, and a completeness guard fails when a
route or environment variable exists in source but not in the manifest. The point
is not prose quality - it is that nothing model- or operator-facing can be
undocumented.

    ./scripts/gen-interactions.py            # write docs/interactions.md
    ./scripts/gen-interactions.py --check    # exit 1 on undocumented or stale

Manifest: docs/interactions.json  {"routes": {...}, "env": {...}}
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "backend" / "src"
MANIFEST = ROOT / "docs" / "interactions.json"
OUTPUT = ROOT / "docs" / "interactions.md"

ROUTE_RE = re.compile(r'\.route\(\s*"([^"]+)"\s*,\s*(.{0,240}?)\)\s*(?:\n|$)', re.S)
METHOD_RE = re.compile(r'\b(get|put|post|patch|delete)\s*\(')
ENV_RE = re.compile(r'env::var\("([A-Z0-9_]+)"\)')


def discover():
    routes, envs = {}, {}
    for path in sorted(SRC.rglob("*.rs")):
        text = path.read_text(encoding="utf-8", errors="replace")
        rel = path.relative_to(ROOT).as_posix()
        for match in ROUTE_RE.finditer(text):
            route, tail = match.group(1), match.group(2)
            methods = sorted({m.upper() for m in METHOD_RE.findall(tail)})
            key = f"{'/'.join(methods) or 'ANY'} {route}"
            routes.setdefault(key, rel)
        for var in ENV_RE.findall(text):
            envs.setdefault(var, rel)
    return routes, envs


def load_manifest():
    if not MANIFEST.exists():
        return {"routes": {}, "env": {}}
    return json.loads(MANIFEST.read_text())


def check(routes, envs, manifest):
    problems = []
    for key, where in sorted(routes.items()):
        entry = manifest.get("routes", {}).get(key)
        if entry is None:
            problems.append(f"undocumented route {key!r}  (registered in {where})")
        elif not entry.get("purpose"):
            problems.append(f"route {key!r} has no purpose text")
    for var, where in sorted(envs.items()):
        entry = manifest.get("env", {}).get(var)
        if entry is None:
            problems.append(f"undocumented env var {var!r}  (read in {where})")
        elif not entry.get("purpose"):
            problems.append(f"env var {var!r} has no purpose text")
    for key in sorted(set(manifest.get("routes", {})) - set(routes)):
        problems.append(f"stale manifest entry {key!r} (no such route in source)")
    for key in sorted(set(manifest.get("env", {})) - set(envs)):
        problems.append(f"stale manifest entry {key!r} (env var no longer read)")
    return problems


def render(routes, envs, manifest):
    lines = [
        "# Interaction reference",
        "",
        "<!-- GENERATED by scripts/gen-interactions.py - do not edit by hand. -->",
        "<!-- Verified fresh by `scripts/gen-interactions.py --check`. -->",
        "",
        "Trefoil's operator- and client-facing surface, derived from the route table in",
        "`backend/src` and the `env::var` calls in the same tree. A route or variable that",
        "exists in source but not in `docs/interactions.json` fails the check, so the",
        "catalog cannot silently fall behind the code.",
        "",
        "`verified` means the behaviour below was exercised against a running instance and",
        "the observed response recorded; everything else is declared but unproven.",
        "",
        "**Coverage:** {} routes, {} environment variables. Described: {}/{} routes "
        "({:.0f}%). Verified against a live instance: {}/{} routes.".format(
            len(routes), len(envs),
            sum(1 for r in manifest["routes"].values() if "not yet described" not in r["purpose"]),
            len(routes),
            100.0 * sum(1 for r in manifest["routes"].values() if "not yet described" not in r["purpose"]) / max(len(routes), 1),
            sum(1 for r in manifest["routes"].values() if r.get("verified") == "yes"),
            len(routes),
        ),
        "",
        "## Routes",
        "",
        "| Route | Purpose | Auth | Verified |",
        "|---|---|---|---|",
    ]
    for key in sorted(routes):
        entry = manifest["routes"].get(key, {})
        lines.append(
            "| `{}` | {} | {} | {} |".format(
                key,
                entry.get("purpose", "**UNDOCUMENTED**"),
                entry.get("auth", "?"),
                entry.get("verified", "no"),
            )
        )
    lines += ["", "## Environment", "", "| Variable | Purpose | Verified |", "|---|---|---|"]
    for var in sorted(envs):
        entry = manifest["env"].get(var, {})
        lines.append(f"| `{var}` | {entry.get('purpose', '**UNDOCUMENTED**')} | {entry.get('verified', 'no')} |")
    notes = [r for r in manifest.get("routes", {}).values() if r.get("notes")]
    if notes:
        lines += ["", "## Observed behaviour", ""]
        for key in sorted(routes):
            entry = manifest["routes"][key]
            if entry.get("notes"):
                lines.append(f"### `{key}`")
                lines.append("")
                lines.append(entry["notes"].strip())
                lines.append("")
    lines += [
        "## Known limits of this generator",
        "",
        "- Paths are as registered. A router nested under a prefix (for example",
        "  `.nest(\"/v1\", ...)`) is not resolved, so some paths may be relative.",
        "- Method inference reads the router chain following the path literal; a route",
        "  registered through an indirection will appear as `ANY`.",
        "- Completeness is enforced, truth is not. `verified: yes` is a claim about a",
        "  recorded observation, and the observation lives in the ticket that claims it.",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    routes, envs = discover()
    manifest = load_manifest()
    if args.check:
        problems = check(routes, envs, manifest)
        if problems:
            print(f"interaction docs are out of date ({len(problems)} problem(s)):", file=sys.stderr)
            for problem in problems:
                print(f"  - {problem}", file=sys.stderr)
            return 1
        expected = render(routes, envs, manifest)
        actual = OUTPUT.read_text() if OUTPUT.exists() else ""
        if expected.strip() != actual.strip():
            print("docs/interactions.md is stale relative to source; run scripts/gen-interactions.py", file=sys.stderr)
            return 1
        print(f"ok: {len(routes)} routes and {len(envs)} env vars documented, catalog fresh")
        return 0
    OUTPUT.write_text(render(routes, envs, manifest))
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(routes)} routes, {len(envs)} env vars)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
